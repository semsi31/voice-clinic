import { createReadStream, createWriteStream, readFileSync, writeFileSync } from "node:fs";
import { createInterface } from "node:readline";
import { basename } from "node:path";

const LOCAL_USER_ID = "ec441a7b-bf03-4655-8e02-923a7e5bf110";
const CLOUD_USER_ID = "242f8f1f-e9e7-4701-b70e-f81190db6a9e";

/** FK-safe import order (parents before children). */
const TABLE_ORDER = [
  "patient_transactions",
  "transaction_payments",
  "import_batches",
  "import_rows",
  "stock_products",
  "stock_movements",
  "cargo_records",
  "reminders",
  "finance_records",
  "documents",
  "web_requests",
];

/** Never migrate these from local dump. */
const SKIP_TABLES = new Set([
  "profiles", // references auth.users; cloud user UUID differs
]);

const inputPath = process.argv[2] ?? "supabase/local-public-data.sql";
const outputPath = process.argv[3] ?? "supabase/cloud-import-safe.sql";

const raw = readFileSync(inputPath, "utf8");

/** @type {Map<string, string>} */
const sections = new Map();

const sectionRegex =
  /--\n-- Data for Name: ([a-z_]+); Type: TABLE DATA; Schema: public; Owner: [^\n]+\n--\n\n([\s\S]*?)(?=\n--\n-- Data for Name:|\n--\n-- Name: |\nRESET ALL;|\n--\n-- PostgreSQL database dump complete)/g;

let match;
while ((match = sectionRegex.exec(raw)) !== null) {
  const table = match[1];
  let body = match[2].trim();
  if (!body) {
    sections.set(table, "");
    continue;
  }
  sections.set(table, body);
}

const found = [...sections.keys()];
const missing = TABLE_ORDER.filter((t) => !sections.has(t));
const extras = found.filter((t) => !TABLE_ORDER.includes(t) && !SKIP_TABLES.has(t));

console.log("Found public tables:", found.join(", ") || "(none)");
if (missing.length) console.log("Missing from dump (ok if empty):", missing.join(", "));
if (extras.length) console.log("Extra tables skipped from order list:", extras.join(", "));
console.log("Skipped by policy:", [...SKIP_TABLES].join(", "));

const out = [];
out.push(`-- Safe cloud import generated by ${basename(new URL(import.meta.url).pathname)}`);
out.push(`-- Source: ${inputPath}`);
out.push(`-- Policy: public app tables only, ON CONFLICT DO NOTHING, no truncate/drop`);
out.push(`-- User remap: ${LOCAL_USER_ID} -> ${CLOUD_USER_ID}`);
out.push(`SET session_replication_role = replica;`);
out.push(`SET check_function_bodies = false;`);
out.push(`SET client_min_messages = warning;`);
out.push(`SET search_path = public;`);
out.push("");

/** @type {Record<string, number>} */
const planned = {};

for (const table of TABLE_ORDER) {
  let body = sections.get(table) ?? "";
  if (!body) {
    planned[table] = 0;
    out.push(`-- ${table}: no data`);
    out.push("");
    continue;
  }

  body = body.split(LOCAL_USER_ID).join(CLOUD_USER_ID);

  // Ensure INSERT ... ON CONFLICT DO NOTHING;
  if (/^INSERT INTO/i.test(body)) {
    body = body.replace(/;\s*$/, "\nON CONFLICT DO NOTHING;");
    const valueRows = (body.match(/\n\t\(/g) || []).length;
    planned[table] = valueRows || (body.includes("VALUES") ? 1 : 0);
  } else if (/^COPY /i.test(body)) {
    throw new Error(`COPY format not supported for safe merge: ${table}`);
  } else {
    planned[table] = 0;
  }

  out.push(`-- ${table}`);
  out.push(body);
  out.push("");
}

out.push(`-- Ensure cloud admin profile exists (idempotent)`);
out.push(
  `INSERT INTO public.profiles (id, full_name, is_active)
VALUES ('${CLOUD_USER_ID}', 'voiceklinik@gmail.com', true)
ON CONFLICT (id) DO NOTHING;`,
);
out.push("");
out.push(`SET session_replication_role = DEFAULT;`);
out.push("");

writeFileSync(outputPath, out.join("\n"), "utf8");

console.log("\nPlanned row inserts (approx from VALUES lines):");
for (const [table, count] of Object.entries(planned)) {
  console.log(`  ${table.padEnd(28)} ${count}`);
}
console.log(`\nWrote ${outputPath}`);
